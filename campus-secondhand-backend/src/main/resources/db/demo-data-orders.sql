-- ====================================================================
-- ①.5 支付单 + 订单支付方式（从订单派生，不手写第二份金额）
-- ====================================================================
-- ★ 为什么要给演示订单补支付单 ★
--
-- 改造后「订单已付款」这个事实由**支付单**背书：t_order.pay_time 只是展示用的
-- 时间戳，真正的凭证在 t_payment（渠道 / 流水号 / 金额 / 回调原文）。
-- 如果演示数据里只有 pay_time、没有支付单，就等于演示一个**凭证缺失的已付款订单** ——
-- 支付记录页一片空白、按渠道统计全是 0，看起来像支付功能没做。
--
-- ★ 金额与时序一律从 t_order 取，不重复写死 ★
-- 手写第二份金额是这类种子最常见的事故来源：改了订单金额、忘了改支付单，
-- 于是「订单 45 元、支付单 65 元」这种自相矛盾的数据被演示给老师看。
-- 这里用 INSERT ... SELECT 派生，从结构上杜绝这种不一致。
--
-- 约定：
--   · id / out_trade_no 用 'pay_' + 订单号（与运行时发号器同形：pay_ + 20 位 = 24 字符）
--   · 只有 pay_time 非空的订单才有支付单 —— 待付款订单本来就不该有
--   · 演示订单标注为 demo 渠道，与管理端「线下代收」的 offline 区分开
