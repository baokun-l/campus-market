-- 待付款订单：补上支付截止时间，否则「超时未付款」在工作台里永远判不出来
-- （SLA 判定看 create_time 兜底仍然有效，但 pay_expire_at 为空时
--   超时关单任务扫不到它 —— 演示里正好需要一个「即将超时」的单子）
--
-- ★★ 必须是 NOW() + 24h，不能是 create_time + 24h ★★
-- 这单的 create_time 是 2026-09-16（种子里刻意压成"几天前"来演示超时标红），
-- 按 create_time 算出来的截止时间**在灌数据的那一刻就已经过去了** ——
-- 结果就是演示刚启动 5 分钟内，超时关单任务把这单自动关掉，
-- 演示者还没开口，「待付款」这一栏就空了，而且日志里只有一句正常的任务日志。
-- 真机实测踩到过：见 docs/后端设计说明.md 附二十三 23.9。
UPDATE t_order SET pay_expire_at = DATE_ADD(NOW(), INTERVAL 24 HOUR)
WHERE id = '20260916201512001' AND pay_time IS NULL;


