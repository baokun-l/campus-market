-- ====================================================================
-- ⑤ 校验：状态分布 + 日志/会话条数
-- ====================================================================
SELECT '订单(全部)' AS 项, COUNT(*) AS 数量 FROM t_order
UNION ALL SELECT '  待付款',   COUNT(*) FROM t_order WHERE status = 'pending_payment'
UNION ALL SELECT '  待发货',   COUNT(*) FROM t_order WHERE status = 'pending_ship'
UNION ALL SELECT '  已发货',   COUNT(*) FROM t_order WHERE status = 'shipped'
UNION ALL SELECT '  已收货',   COUNT(*) FROM t_order WHERE status = 'received'
UNION ALL SELECT '  已完成',   COUNT(*) FROM t_order WHERE status = 'completed'
UNION ALL SELECT '  退款中',   COUNT(*) FROM t_order WHERE status = 'refunding'
UNION ALL SELECT '  已取消',   COUNT(*) FROM t_order WHERE status = 'cancelled'
UNION ALL SELECT '订单操作日志', COUNT(*) FROM t_order_log
UNION ALL SELECT '私信消息',   COUNT(*) FROM t_message
UNION ALL SELECT '私信会话数', COUNT(DISTINCT session_id) FROM t_message
UNION ALL SELECT '支付单',     COUNT(*) FROM t_payment
UNION ALL SELECT '支付单(成功)', COUNT(*) FROM t_payment WHERE status = 'success'
UNION ALL SELECT '成交额(已付款状态合计)', IFNULL(SUM(amount), 0) FROM t_order
    WHERE status IN ('pending_ship', 'shipped', 'received', 'completed');

